create table if not exists public.packages (
  id bigint generated by default as identity primary key,
  name text unique not null,
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.versions (
  id bigint generated by default as identity primary key,
  package_id bigint not null references public.packages(id) on delete cascade,
  version text not null,
  release_date timestamptz,
  changelog text,
  created_at timestamptz not null default now(),
  -- Release notes (migrations/004_add_version_release_notes.sql).
  release_type text check (release_type in ('feature', 'hotfix')),
  summary text,
  service_action text,
  notes_updated_at timestamptz,
  notes_updated_by text check (char_length(notes_updated_by) <= 200),
  unique (package_id, version)
);

create index if not exists idx_versions_package_id on public.versions(package_id);

alter table public.packages enable row level security;
alter table public.versions enable row level security;
